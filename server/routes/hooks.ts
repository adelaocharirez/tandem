import { eq } from 'drizzle-orm';
import type { FastifyInstance, FastifyReply, FastifyRequest } from 'fastify';
import { rooms, type AgentRow } from '../db/schema';
import { unauthorized } from '../lib/http';
import { repoRelative } from '../lib/paths';
import { formatDigest, formatSessionStart } from '../mcp/format';
import { checkEdit, endSession, peekDigest, sessionBriefing, touchAgent } from '../services/collab';
import { authenticateAgent } from '../services/rooms';
import { renderSetupScript } from '../setupScript';
import { bearerToken, type RouteEnv } from './env';

/** The parts of Claude Code's hook payload we read. Everything else is ignored. */
interface HookPayload {
  cwd?: unknown;
  reason?: unknown;
  tool_input?: { file_path?: unknown; notebook_path?: unknown };
}

const text = (value: unknown): string | undefined => (typeof value === 'string' && value ? value : undefined);

/**
 * Server-side Claude Code hooks.
 *
 * Each hook on the developer's machine is a one-line curl that forwards
 * Claude Code's hook JSON here and prints the response. Claude Code reads
 * that response as the hook's output, so these routes answer in its format:
 * an empty 204 for "nothing to say, carry on", or a JSON object with
 * `hookSpecificOutput` to add context or deny a tool call.
 *
 * A hook must never get in the way when Tandem is down: curl fails, prints
 * nothing, and Claude Code treats that as a non-blocking error.
 */
export function registerHookRoutes(app: FastifyInstance, env: RouteEnv): void {
  const { ctx } = env;

  const agentFor = async (request: FastifyRequest): Promise<AgentRow> => {
    const token = bearerToken(request);
    const agent = token ? await authenticateAgent(ctx.db, token) : null;
    if (!agent) throw unauthorized('Missing, wrong, or revoked Tandem agent token.');
    return agent;
  };
  const roomName = async (agent: AgentRow) =>
    (await ctx.db.select({ name: rooms.name }).from(rooms).where(eq(rooms.id, agent.roomId)))[0]?.name ?? 'room';
  const nothing = (reply: FastifyReply) => reply.code(204).send();

  // The setup script itself. Public: it contains no secrets, only this server's address.
  app.get('/setup.js', async (request, reply) =>
    reply.type('text/javascript; charset=utf-8').header('cache-control', 'no-store').send(renderSetupScript(env.publicUrl(request))),
  );

  // Lets the setup script check a token and greet the agent by name.
  app.get('/api/agent/whoami', async (request) => {
    const agent = await agentFor(request);
    return { agent: agent.name, room: await roomName(agent) };
  });

  // SessionStart: orient a fresh Claude Code session before its first prompt.
  app.post('/api/agent/hooks/session-start', async (request) => {
    const agent = await agentFor(request);
    await touchAgent(ctx, agent, null);
    const briefing = await sessionBriefing(ctx, agent);
    return {
      hookSpecificOutput: {
        hookEventName: 'SessionStart',
        additionalContext: formatSessionStart(await roomName(agent), agent.name, briefing),
      },
    };
  });

  // UserPromptSubmit: mention anything new, once. Silent when the room is quiet.
  app.post('/api/agent/hooks/prompt', async (request, reply) => {
    const agent = await agentFor(request);
    await touchAgent(ctx, agent, null);
    const digest = formatDigest(await roomName(agent), await peekDigest(ctx, agent));
    if (!digest) return nothing(reply);
    return { hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: digest } };
  });

  // PreToolUse on Edit/Write: refuse edits to files another agent holds; claim the rest.
  app.post('/api/agent/hooks/pre-edit', async (request, reply) => {
    const agent = await agentFor(request);
    const body = (request.body ?? {}) as HookPayload;
    const file = text(body.tool_input?.file_path) ?? text(body.tool_input?.notebook_path);
    const root = text(request.headers['x-tandem-root']) ?? text(body.cwd);
    const path = file ? repoRelative(root, file) : null;
    // Files outside the project (temp files, home-directory config) are none of the room's business.
    if (!path) return nothing(reply);

    await touchAgent(ctx, agent, 'edit');
    const check = await checkEdit(ctx, agent, path);
    if (check.allowed) return nothing(reply);

    const theirs = check.heldPath === check.path ? '' : ` (their claim covers ${check.heldPath})`;
    const note = check.note ? ` They said: "${check.note}".` : '';
    return {
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason:
          `Tandem blocked this edit: ${check.path} is claimed by ${check.holderName}${theirs}.${note} ` +
          'Do not edit this file or work around the block. Tell your user who holds it. ' +
          'If you need it, use the tandem ask_peer tool to ask them to release it, and work on something else meanwhile.',
      },
    };
  });

  // SessionEnd: the terminal closed, so stop showing this Claude as busy.
  app.post('/api/agent/hooks/session-end', async (request, reply) => {
    const agent = await agentFor(request);
    const reason = text((request.body as HookPayload | undefined)?.reason);
    // /clear and /resume end a "session" but the person is still sitting there working.
    if (reason !== 'clear' && reason !== 'resume') await endSession(ctx, agent);
    return nothing(reply);
  });
}
